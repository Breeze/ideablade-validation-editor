// Generates a test project for sources taken from folders (Add folder…, patterns in the project's "sources"): a folder
// of TypeScript view models, in client/src/app/view-models and its subfolders, and a folder of C# DTOs, in
// server/Dtos and its subfolders, 15-20 files each, plus a metadata file for some of them and folders.ivproj. The
// project lists the TypeScript folder as a pattern; the C# one is there to add with Add folder…. The output is always
// the same: `node generate.cjs` writes it again (and removes what it wrote before).
const fs = require('node:fs');
const path = require('node:path');

const dir = __dirname;

const fields = {
  name: ['string', 'string'],
  code: ['string', 'string'],
  email: ['string', 'string'],
  phone: ['string', 'string'],
  notes: ['string', 'string'],
  amount: ['number', 'decimal'],
  quantity: ['number', 'int'],
  discount: ['number', 'decimal'],
  startDate: ['Date', 'DateTime'],
  endDate: ['Date', 'DateTime'],
  isActive: ['boolean', 'bool'],
  status: ['string', 'string'],
};

/** Each model: its file (relative to its folder) and its properties. */
const viewModels = [
  ['customer-form.ts', 'CustomerForm', ['name', 'email', 'phone', 'notes']],
  ['customer-search.ts', 'CustomerSearch', ['name', 'code', 'status']],
  ['address-form.ts', 'AddressForm', ['name', 'code', 'notes']],
  ['contact-form.ts', 'ContactForm', ['name', 'email', 'phone']],
  ['login-form.ts', 'LoginForm', ['email', 'notes']],
  ['profile-form.ts', 'ProfileForm', ['name', 'email', 'phone', 'isActive']],
  ['settings-form.ts', 'SettingsForm', ['code', 'isActive', 'notes']],
  ['invite-form.ts', 'InviteForm', ['email', 'name']],
  ['orders/order-form.ts', 'OrderForm', ['code', 'amount', 'discount', 'startDate']],
  ['orders/order-line-form.ts', 'OrderLineForm', ['code', 'quantity', 'amount']],
  ['orders/order-search.ts', 'OrderSearch', ['code', 'status', 'startDate', 'endDate']],
  ['orders/return-form.ts', 'ReturnForm', ['code', 'quantity', 'notes']],
  ['orders/discount-form.ts', 'DiscountForm', ['code', 'discount', 'startDate', 'endDate']],
  ['projects/project-form.ts', 'ProjectForm', ['name', 'code', 'startDate', 'endDate']],
  ['projects/task-form.ts', 'TaskForm', ['name', 'status', 'startDate', 'endDate']],
  ['projects/time-entry-form.ts', 'TimeEntryForm', ['quantity', 'startDate', 'notes']],
  ['projects/milestone-form.ts', 'MilestoneForm', ['name', 'endDate', 'status']],
  ['projects/budget-form.ts', 'BudgetForm', ['code', 'amount', 'startDate', 'endDate']],
];

const dtos = [
  ['CustomerDto.cs', 'CustomerDto', ['name', 'email', 'phone', 'status']],
  ['AddressDto.cs', 'AddressDto', ['name', 'code', 'notes']],
  ['ContactDto.cs', 'ContactDto', ['name', 'email', 'phone']],
  ['ProductDto.cs', 'ProductDto', ['name', 'code', 'amount', 'isActive']],
  ['OrderDto.cs', 'OrderDto', ['code', 'amount', 'discount', 'startDate']],
  ['OrderLineDto.cs', 'OrderLineDto', ['code', 'quantity', 'amount']],
  ['InvoiceDto.cs', 'InvoiceDto', ['code', 'amount', 'startDate', 'endDate']],
  ['PaymentDto.cs', 'PaymentDto', ['code', 'amount', 'startDate']],
  ['ShipmentDto.cs', 'ShipmentDto', ['code', 'status', 'startDate', 'endDate']],
  ['ReturnDto.cs', 'ReturnDto', ['code', 'quantity', 'notes']],
  ['ProjectDto.cs', 'ProjectDto', ['name', 'code', 'startDate', 'endDate']],
  ['TaskDto.cs', 'TaskDto', ['name', 'status', 'startDate', 'endDate']],
  ['Admin/UserDto.cs', 'UserDto', ['name', 'email', 'isActive']],
  ['Admin/RoleDto.cs', 'RoleDto', ['name', 'code']],
  ['Admin/TenantDto.cs', 'TenantDto', ['name', 'code', 'isActive']],
  ['Admin/AuditEntryDto.cs', 'AuditEntryDto', ['code', 'notes', 'startDate']],
  ['Admin/ApiKeyDto.cs', 'ApiKeyDto', ['name', 'code', 'endDate']],
];

const pascal = (name) => name[0].toUpperCase() + name.slice(1);
const optional = (field) => ['notes', 'discount', 'endDate', 'phone'].includes(field);

const clientDir = path.join(dir, 'client');
const serverDir = path.join(dir, 'server');
fs.rmSync(clientDir, { recursive: true, force: true });
fs.rmSync(serverDir, { recursive: true, force: true });

const write = (file, text) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
};

for (const [file, name, props] of viewModels) {
  const lines = props.map((p) => `  ${p}${optional(p) ? '?' : ''}: ${fields[p][0]}${optional(p) ? ' | null' : ''};`);
  write(path.join(clientDir, 'src', 'app', 'view-models', file), `/** Test view model, generated by generate.cjs. */\nexport interface ${name} {\n${lines.join('\n')}\n}\n`);
}

for (const [file, name, props] of dtos) {
  const lines = props.map((p) => `    public ${fields[p][1]}${optional(p) && fields[p][1] !== 'string' ? '?' : ''} ${pascal(p)} { get; set; }`);
  const ns = file.includes('/') ? 'FolderSources.Dtos.Admin' : 'FolderSources.Dtos';
  write(
    path.join(serverDir, 'Dtos', file),
    `// Test DTO, generated by generate.cjs.\nnamespace ${ns};\n\npublic class ${name}\n{\n${lines.join('\n')}\n}\n`,
  );
}

// Rules for a few of them, so the project opens with something to edit.
const rule = (field) => {
  const p = {};
  if (!optional(field)) p.required = true;
  if (field === 'email') p.validators = [{ name: 'email' }];
  else if (field === 'phone') p.validators = [{ name: 'phone' }];
  else if (['name', 'code', 'notes', 'status'].includes(field)) p.maxLength = field === 'notes' ? 2000 : 50;
  else if (['amount', 'quantity', 'discount'].includes(field)) p.validators = [{ name: 'range', context: { minValue: 0 } }];
  return p;
};
const metadata = {
  $schema: 'https://raw.githubusercontent.com/Breeze/ideablade-validation/main/spec/validation-metadata.schema.json',
  $comment: 'Test metadata for sources taken from folders, generated by generate.cjs.',
};
for (const [, name, props] of [viewModels[0], viewModels[4], viewModels[8], viewModels[13], dtos[0], dtos[4]]) {
  metadata[name] = { properties: Object.fromEntries(props.map((p) => [p, rule(p)])) };
}
fs.writeFileSync(path.join(dir, 'folders.metadata.json'), JSON.stringify(metadata, null, 2) + '\n');

fs.writeFileSync(
  path.join(dir, 'folders.ivproj'),
  JSON.stringify(
    {
      $comment:
        'A test project for sources taken from folders, generated by generate.cjs. The TypeScript view models are a pattern: new files in that folder are picked up as they appear. server/Dtos is there to add with Add folder….',
      metadata: ['folders.metadata.json'],
      sources: ['client/src/app/view-models/**/*.{ts,cs}'],
      otherValidators: [],
      camelCase: true,
    },
    null,
    2,
  ) + '\n',
);
console.log(`${viewModels.length} view models, ${dtos.length} DTOs and folders.ivproj in ${dir}`);
