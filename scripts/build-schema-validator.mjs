// Compiles the library's JSON Schema into a standalone validator module (src/generated/), so the app checks files
// against the schema without Ajv compiling code at runtime: the app's Content-Security-Policy has no 'unsafe-eval'.
// The schema comes from the installed ideablade-validation package, so it always matches the library version.
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const schemaPath = require.resolve('ideablade-validation/schema/validation-metadata.schema.json');
const schema = JSON.parse(await readFile(schemaPath, 'utf8'));
const version = JSON.parse(await readFile(require.resolve('ideablade-validation/package.json'), 'utf8')).version;

const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true } });
const validate = ajv.compile(schema);
// The standalone code require()s one runtime helper (string length in code points); inline it to keep the module pure ESM.
const code = standaloneCode(ajv, validate).replaceAll(
  'require("ajv/dist/runtime/ucs2length").default',
  '((s) => [...s].length)',
);
if (code.includes('require(')) throw new Error('The generated schema validator still require()s a module; inline it too.');

await mkdir('src/generated', { recursive: true });
await writeFile('src/generated/schema-validator.js', `// Generated by scripts/build-schema-validator.mjs from ideablade-validation ${version}. Do not edit.\n${code}`);
await writeFile(
  'src/generated/schema-validator.d.ts',
  `// Generated by scripts/build-schema-validator.mjs. Do not edit.
export interface SchemaError { instancePath: string; schemaPath: string; keyword: string; params: Record<string, unknown>; message?: string }
declare const validate: ((data: unknown) => boolean) & { errors?: SchemaError[] | null };
export default validate;
export const schemaVersion: string;
`,
);
await writeFile('src/generated/schema-validator.js', `\nexport const schemaVersion = ${JSON.stringify(version)};\n`, { flag: 'a' });
console.log(`Schema validator generated from ideablade-validation ${version}.`);
